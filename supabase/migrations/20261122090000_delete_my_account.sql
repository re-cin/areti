-- Lets a signed-in user permanently delete their own account.
-- Deleting the auth user also deletes all their rows (every table references auth.users
-- with "on delete cascade"). The app removes their profile picture file first.
create or replace function public.delete_my_account()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
begin
  if uid is null then
    raise exception 'Not signed in';
  end if;
  delete from auth.users where id = uid;
end;
$$;

revoke execute on function public.delete_my_account() from public, anon;
grant execute on function public.delete_my_account() to authenticated;
